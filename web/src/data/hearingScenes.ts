/**
 * 打合せのロールプレイに使うペルソナ（10件）。家族・名前・発言・事情はすべて架空。
 *
 * 作り方：
 * - 骨格（葬儀の形・喪主から見た続柄・故人の年齢・亡くなった場所・葬儀までの日数・互助会）は、
 *   基幹システムの施行の記録（2022年以降・2,020件）で件数の多い組み合わせから選んだ（basis に記す）
 * - 特定の選択肢を考えさせるための仕掛けは入れない。hidden には、どの家族にもある普通の情報
 *   （故人の人柄、知らせたい人、宗派やお寺、費用の考え、家族の事情）を置き、担当者が尋ねたときだけ家族が話す
 * - 同じペルソナで、経験の違う担当者（ベテラン・中堅・新人）がロールプレイし、何をどの順で尋ね、どう判断したかを比べる
 * - 家族役のモデルは、card・hidden・persona にないことを作らない
 */

export interface HearingFamilyMember {
  /** 画面に出す呼び名（例：長男） */
  readonly label: string;
  /** 話し方と気持ち。家族役のモデルに渡す */
  readonly persona: string;
}

export interface HiddenFact {
  readonly id: string;
  /** 誰が知っているか（family の label） */
  readonly heldBy: string;
  readonly fact: string;
  /** どう尋ねられたら話すか */
  readonly revealWhen: string;
}

export interface HearingScene {
  readonly id: string;
  readonly title: string;
  /** 記録のどの組み合わせを骨格にしたか */
  readonly basis: string;
  readonly card: readonly string[];
  readonly family: readonly HearingFamilyMember[];
  /** 家族の最初の発言（担当者のお悔やみのあと） */
  readonly opening: readonly { readonly speaker: string; readonly text: string }[];
  readonly hidden: readonly HiddenFact[];
}

